#include "swan/svm.h"
#include "swan/optimization.h"
#include <assert.h>
#include <stdio.h>

int main(void) {
    SwanIRModule module={0};
    SwanIRFunction *fn=swan_ir_add_function(&module,"main",SWAN_IR_I64,NULL,0);
    assert(fn);
    SwanIRBlock *entry=swan_ir_add_block(fn,"entry");
    assert(entry);
    SwanIRInst a={0}; a.op=SWAN_IR_CONST; a.type=SWAN_IR_I64; a.immediate=6;
    uint32_t av=swan_ir_add_inst(fn,entry,a); assert(av);
    SwanIRInst b={0}; b.op=SWAN_IR_CONST; b.type=SWAN_IR_I64; b.immediate=7;
    uint32_t bv=swan_ir_add_inst(fn,entry,b); assert(bv);
    SwanIRInst mul={0}; mul.op=SWAN_IR_MUL; mul.type=SWAN_IR_I64; mul.a=av; mul.b=bv;
    uint32_t product=swan_ir_add_inst(fn,entry,mul); assert(product);
    assert(swan_ir_terminate(entry,(SwanIRTerm){SWAN_IR_RET,product,0,0}));
    char error[256]={0}; int64_t result=0;
    assert(swan_svm_run(&module,"main",100,&result,error,sizeof(error)));
    assert(result==42);
    assert(swan_ir_optimize(&module,error,sizeof(error)));
    assert(swan_svm_run(&module,"main",100,&result,error,sizeof(error)));
    assert(result==42);
    FILE *artifact=tmpfile(); assert(artifact);
    assert(swan_svm_write_module(artifact,&module));
    rewind(artifact);
    SwanIRModule loaded={0};
    assert(swan_svm_read_module(artifact,&loaded,error,sizeof(error)));
    fclose(artifact);
    assert(swan_svm_run(&loaded,"main",100,&result,error,sizeof(error)));
    assert(result==42);
    FILE *truncated=tmpfile();assert(truncated);
    assert(swan_svm_write_bytes(truncated,"SWANVM01",8));
    assert(swan_svm_write_u32(truncated,SWAN_SVM_VERSION));
    assert(swan_svm_write_u32(truncated,0));
    assert(swan_svm_write_u64(truncated,4));
    rewind(truncated);SwanIRModule rejected={0};
    assert(!swan_svm_read_module(truncated,&rejected,error,sizeof(error)));
    fclose(truncated);
    FILE *trailing=tmpfile();assert(trailing);
    assert(swan_svm_write_bytes(trailing,"SWANVM01",8));
    assert(swan_svm_write_u32(trailing,SWAN_SVM_VERSION));
    assert(swan_svm_write_u32(trailing,0));
    assert(swan_svm_write_u64(trailing,4));
    assert(swan_svm_write_u32(trailing,0));
    assert(fputc(0xff,trailing)!=EOF);assert(fflush(trailing)==0);assert(fseek(trailing,0,SEEK_END)==0&&ftell(trailing)==29);
    rewind(trailing);assert(!swan_svm_read_module(trailing,&rejected,error,sizeof(error)));
    fclose(trailing);
    SwanIRModule shared={0};
    SwanIRType pointer_param[]={SWAN_IR_PTR};
    SwanIRFunction *writer=swan_ir_add_function(&shared,"write_value",SWAN_IR_VOID,pointer_param,1);assert(writer);
    SwanIRBlock *writer_entry=swan_ir_add_block(writer,"entry");assert(writer_entry);
    SwanIRInst stored={0};stored.op=SWAN_IR_CONST;stored.type=SWAN_IR_I64;stored.immediate=99;
    uint32_t stored_value=swan_ir_add_inst(writer,writer_entry,stored);assert(stored_value);
    SwanIRInst store={0};store.op=SWAN_IR_STORE;store.type=SWAN_IR_VOID;store.a=1;store.b=stored_value;
    assert(swan_ir_add_inst(writer,writer_entry,store)==0);
    assert(swan_ir_terminate(writer_entry,(SwanIRTerm){SWAN_IR_RET,0,0,0}));
    SwanIRFunction *shared_main=swan_ir_add_function(&shared,"main",SWAN_IR_I64,NULL,0);assert(shared_main);
    SwanIRBlock *shared_entry=swan_ir_add_block(shared_main,"entry");assert(shared_entry);
    SwanIRInst slot={0};slot.op=SWAN_IR_ALLOCA;slot.type=SWAN_IR_PTR;
    uint32_t slot_value=swan_ir_add_inst(shared_main,shared_entry,slot);assert(slot_value);
    SwanIRInst call={0};call.op=SWAN_IR_CALL;call.type=SWAN_IR_VOID;call.symbol="write_value";
    call.incoming=calloc(1,sizeof(*call.incoming));assert(call.incoming);call.incoming_count=1;call.incoming[0]=(SwanIRIncoming){slot_value,0};
    assert(swan_ir_add_inst(shared_main,shared_entry,call)==0);
    SwanIRInst load={0};load.op=SWAN_IR_LOAD;load.type=SWAN_IR_I64;load.a=slot_value;
    uint32_t loaded_value=swan_ir_add_inst(shared_main,shared_entry,load);assert(loaded_value);
    assert(swan_ir_terminate(shared_entry,(SwanIRTerm){SWAN_IR_RET,loaded_value,0,0}));
    assert(swan_svm_run(&shared,"main",100,&result,error,sizeof(error)));assert(result==99);
    swan_ir_destroy(&shared);
    SwanIRModule narrow={0};
    SwanIRFunction *narrow_fn=swan_ir_add_function(&narrow,"wrap8",SWAN_IR_I8,NULL,0);assert(narrow_fn);
    SwanIRBlock *narrow_entry=swan_ir_add_block(narrow_fn,"entry");assert(narrow_entry);
    SwanIRInst max8={0};max8.op=SWAN_IR_CONST;max8.type=SWAN_IR_I8;max8.immediate=127;
    uint32_t max8v=swan_ir_add_inst(narrow_fn,narrow_entry,max8);
    SwanIRInst one8={0};one8.op=SWAN_IR_CONST;one8.type=SWAN_IR_I8;one8.immediate=1;
    uint32_t one8v=swan_ir_add_inst(narrow_fn,narrow_entry,one8);
    SwanIRInst add8={0};add8.op=SWAN_IR_ADD;add8.type=SWAN_IR_I8;add8.a=max8v;add8.b=one8v;
    uint32_t wrap8=swan_ir_add_inst(narrow_fn,narrow_entry,add8);
    assert(swan_ir_terminate(narrow_entry,(SwanIRTerm){SWAN_IR_RET,wrap8,0,0}));
    assert(swan_svm_run(&narrow,"wrap8",100,&result,error,sizeof(error)));assert(result==-128);
    assert(swan_ir_optimize(&narrow,error,sizeof(error)));
    assert(swan_svm_run(&narrow,"wrap8",100,&result,error,sizeof(error)));assert(result==-128);
    swan_ir_destroy(&narrow);
    swan_ir_destroy(&loaded);
    swan_ir_destroy(&module);
        puts("PASS: SVM executes and optimizes portable typed IR");
    return 0;
}
