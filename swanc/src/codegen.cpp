const char* cType(const std::string& t){if(t=="void")return "void";if(t=="bool")return "_Bool";if(t=="int"||t=="i32")return "int32_t";if(t=="i8")return "int8_t";if(t=="i16")return "int16_t";if(t=="i64")return "int64_t";if(t=="u8")return "uint8_t";if(t=="u16")return "uint16_t";if(t=="u32")return "uint32_t";if(t=="u64")return "uint64_t";if(t=="f32")return "float";if(t=="f64")return "double";if(t=="varint")return "intptr_t";return t.c_str();}
static std::string pad(int n){return std::string(static_cast<std::size_t>(n)*2,' ');}
std::string CEmitter::emitExpr(const Expr& e)const{if(auto p=dynamic_cast<const LiteralExpr*>(&e)){if(p->value=="true")return "1";if(p->value=="false")return "0";if(p->value=="null")return "NULL";return p->value;}if(auto p=dynamic_cast<const NameExpr*>(&e))return p->name;if(auto p=dynamic_cast<const UnaryExpr*>(&e)){std::string op=p->op==TokenKind::Minus?"-":"!";return "("+op+emitExpr(*p->rhs)+")";}if(auto p=dynamic_cast<const BinaryExpr*>(&e)){std::string op;switch(p->op){case TokenKind::Plus:op="+";break;case TokenKind::Minus:op="-";break;case TokenKind::Star:op="*";break;case TokenKind::Slash:op="/";break;case TokenKind::Percent:op="%";break;case TokenKind::EqualEqual:op="==";break;case TokenKind::BangEqual:op="!=";break;case TokenKind::Less:op="<";break;case TokenKind::LessEqual:op="<=";break;case TokenKind::Greater:op=">";break;case TokenKind::GreaterEqual:op=">=";break;default:op="?";}return "("+emitExpr(*p->lhs)+" "+op+" "+emitExpr(*p->rhs)+")";}return "0";}
std::string CEmitter::emitStmt(const Stmt& s,int n)const{std::ostringstream o;auto p=pad(n);if(auto b=dynamic_cast<const BlockStmt*>(&s)){o<<p<<"{\n";for(auto& x:b->statements)o<<emitStmt(*x,n+1);o<<p<<"}\n";}else if(auto r=dynamic_cast<const ReturnStmt*>(&s)){o<<p<<"return";if(r->value)o<<" "<<emitExpr(*r->value);o<<";\n";}else if(auto v=dynamic_cast<const VarStmt*>(&s)){o<<p<<(v->mutableValue?"":"const ")<<(v->type.empty()?"int32_t":cType(v->type))<<" "<<v->name;if(v->value)o<<" = "<<emitExpr(*v->value);o<<";\n";}else if(auto e=dynamic_cast<const ExprStmt*>(&s))o<<p<<emitExpr(*e->value)<<";\n";else if(auto i=dynamic_cast<const IfStmt*>(&s)){o<<p<<"if ("<<emitExpr(*i->condition)<<")\n"<<emitStmt(*i->thenBranch,n);if(i->elseBranch)o<<p<<"else\n"<<emitStmt(*i->elseBranch,n);}else if(auto w=dynamic_cast<const WhileStmt*>(&s))o<<p<<"while ("<<emitExpr(*w->condition)<<")\n"<<emitStmt(*w->body,n);return o.str();}
std::string CEmitter::emit(const Module& m)const{
  std::ostringstream o;
  o<<"/* Generated by swanc. Do not edit. */\n#include <stdint.h>\n#include <stddef.h>\n#include <stdbool.h>\n#include <stdlib.h>\n\n";
  // Forward declarations allow functions from any source file to call each other.
  for(const auto& f:m.functions){
    o<<cType(f.returnType)<<" "<<f.name<<"(";
    if(f.params.empty()) o<<"void";
    for(std::size_t i=0;i<f.params.size();++i){
      if(i) o<<", ";
      o<<cType(f.params[i].second)<<" "<<f.params[i].first;
    }
    o<<");\n";
  }
  o<<"\n";
  for(const auto& f:m.functions){
    o<<cType(f.returnType)<<" "<<f.name<<"(";
    if(f.params.empty()) o<<"void";
    for(std::size_t i=0;i<f.params.size();++i){
      if(i) o<<", ";
      o<<cType(f.params[i].second)<<" "<<f.params[i].first;
    }
    o<<")\n"<<emitStmt(*f.body,0)<<"\n";
  }
  return o.str();
}
